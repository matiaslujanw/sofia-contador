import {expect,test} from '@playwright/test';
const company='10000000-0000-4000-8000-000000000011',other='10000000-0000-4000-8000-000000000010';

test('declara y deshace sin compras ni ventas desde comprobantes y lo recupera en preparar mes',async({page})=>{
 await page.setViewportSize({width:820,height:1180});
 await page.goto(`/comprobantes?empresa=${company}`);
 await page.getByRole('button',{name:'Este mes no hubo compras',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Confirmar sin compras'}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(page.getByText('Sin compras confirmado',{exact:true})).toBeVisible();await page.reload();
 await expect(page.getByText('Sin compras confirmado',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:/^Ventas \d/}).click();
 await page.getByRole('button',{name:'Este mes no hubo ventas',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Confirmar sin ventas'}).click();
 await expect(page.getByText('Sin ventas confirmado',{exact:true})).toBeVisible();
 await page.goto(`/preparacion?empresa=${company}&tipo=ventas`);
 await expect(page.getByText('Sin ventas confirmado',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Deshacer sin ventas'}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Deshacer confirmación'}).click();
 await expect(page.getByRole('button',{name:'Este mes no hubo ventas',exact:true})).toBeEnabled();
 await page.goto(`/comprobantes?empresa=${other}`);
 await expect(page.getByRole('button',{name:'Este mes no hubo compras',exact:true})).toBeDisabled();
 await page.getByLabel('Buscar comprobante o CUIT').fill('ninguno');
 await expect(page.getByRole('button',{name:'Este mes no hubo compras',exact:true})).toBeDisabled();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});

test('configura una sola fecha habitual y cambia de mes sin copiar pagos ni perder excepciones',async({page})=>{
 await page.setViewportSize({width:820,height:1180});
 await page.goto(`/calendario?empresa=${company}&mes=2027-01`);
 await page.getByRole('button',{name:'Configurar vencimiento habitual',exact:true}).click();
 const dialog=page.getByRole('dialog');
 await dialog.getByLabel('Impuesto u obligación').fill('TEM habitual sintético');
 await dialog.getByLabel('Vencimiento',{exact:true}).fill('2027-01-31');
 await expect(dialog.getByRole('checkbox',{name:'Repetir todos los meses, conservando el día'})).toBeChecked();
 await dialog.getByLabel('Importe').fill('1000');
 await dialog.getByLabel('Estado').selectOption('paid');
 await dialog.getByLabel('Fecha de pago').fill('2027-01-31');
 await dialog.getByRole('button',{name:'Crear vencimiento'}).click();
 await expect(dialog).toHaveCount(0);await page.reload();
 await expect(page.getByRole('region',{name:'Vencimientos habituales'})).toContainText('día 31');
 await page.goto(`/calendario?empresa=${company}&mes=2027-02`);
 let row=page.getByRole('row').filter({hasText:'TEM habitual sintético'});
 await expect(row.locator('time')).toHaveAttribute('datetime','2027-02-28');await expect(row).toContainText('Pendiente');await expect(row).not.toContainText('1.000,00');
 await row.getByRole('button',{name:'Registrar / ajustar este mes'}).click();
 await expect(dialog.getByLabel('Fecha de pago')).toHaveValue('');
 await dialog.getByLabel('Vencimiento',{exact:true}).fill('2027-02-27');
 await dialog.getByRole('checkbox',{name:'Cambiar solo la fecha de este mes (por feriado o prórroga)'}).check();
 await dialog.getByRole('button',{name:'Guardar cambios'}).click();await expect(dialog).toHaveCount(0);
 await page.goto(`/calendario?empresa=${company}&mes=2027-03`);
 row=page.getByRole('row').filter({hasText:'TEM habitual sintético'});
 await expect(row.locator('time')).toHaveAttribute('datetime','2027-03-31');
 await page.screenshot({path:'/tmp/sofia-vencimientos-ipad.png'});
 await row.getByRole('button',{name:'Registrar / ajustar este mes'}).click();
 await dialog.getByRole('checkbox',{name:'Repetir todos los meses, conservando el día'}).uncheck();
 await dialog.getByRole('button',{name:'Guardar cambios'}).click();await expect(dialog).toHaveCount(0);
 await page.goto(`/calendario?empresa=${company}&mes=2027-04`);
 await expect(page.getByRole('row').filter({hasText:'TEM habitual sintético'})).toHaveCount(0);
 await page.goto(`/calendario?empresa=${company}&mes=2027-01`);
 await expect(page.getByRole('row').filter({hasText:'TEM habitual sintético'})).toContainText('Pagado');
 await page.goto(`/calendario?empresa=${other}&mes=2027-02`);
 await expect(page.getByText('TEM habitual sintético',{exact:true})).toHaveCount(0);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/inicio');await page.screenshot({path:'/tmp/sofia-inicio-pastel.png'});
});
